export function getLang(): Lang {
  if (typeof localStorage === "undefined") return "id";
  return localStorage.getItem("nm-lang") === "en" ? "en" : "id";
}

export function setLang(l: Lang): void {
  try {
    localStorage.setItem("nm-lang", l);
  } catch {
    /* abaikan */
  }
  if (typeof window !== "undefined") {
    window.dispatchEvent(new CustomEvent("nm-lang", { detail: l }));
  }
}
